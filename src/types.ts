/**
 * Типы независимого ядра тренажёра казахского языка (core/).
 * Четыре слоя (К19):
 *   1. Смыслы и сквозные кубики (layer1-meanings)
 *   2. Язык: корни, фонетика, сборщик форм (layer2-kazakh)
 *   3. Источники: независимый слой проверки правил и корпусов фраз (layer3-sources)
 *   4. Движок: 5-шаговый проверяльщик, ступени 1–8, возвраты (layer4-engine)
 */

/** Ряд гласных слова или кусочка: твёрдый (а, о, ұ, ы, я) или мягкий (ә, е, ө, ү, і) */
export type VowelRow = 'hard' | 'soft';

/**
 * Тип последней буквы основы или предыдущего кусочка:
 * - 'V'         — гласная, кроме у, и (а, ә, е, о, ө, ұ, ү, ы, і, я)
 * - 'UI'        — смешанные у, ю, и или согласная й на конце основы
 * - 'R'         — сонорная р
 * - 'L'         — сонорная л
 * - 'ZMN'       — звонкие и носовые з, ж, м, н, ң
 * - 'VOICELESS' — глухие согласные (п, ф, к, қ, т, с, ш, щ, х, ц, ч, һ) и б, в, г, д в заимствованиях
 */
export type StemEndingClass = 'V' | 'UI' | 'R' | 'L' | 'ZMN' | 'VOICELESS';

/** Чередующаяся последняя согласная основы перед гласной: п → б, қ → ғ, к → г */
export type VoicingAlternation = 'п->б' | 'қ->ғ' | 'к->г' | null;

/** Часть речи стартового корня */
export type PartOfSpeech = 'verb' | 'noun' | 'adjective' | 'place';

/** Паспорт корня в слое 2 (К32, 7 полей) */
export interface KazakhRoot {
  id: string;
  /** Слово-основа по-казахски (строчными, без «-у» у глаголов) */
  kz: string;
  /** Перевод на русский (показывается тихой подписью, пока нет галочки «знаю») */
  ru: string;
  /** Для глаголов: перевод в неопределённой форме («пить», «идти туда») */
  ruGloss?: string;
  pos: PartOfSpeech;
  /** Ряд гласных по правилу последней несмешанной гласной */
  vowelRow: VowelRow;
  /** Класс последней буквы основы */
  endingClass: StemEndingClass;
  /** Если основа заканчивается на чередующуюся букву п / қ / к перед гласной */
  alternation: VoicingAlternation;
  /** Особая группа глаголов движения (бар, кел, апар, әкел — для тем 78–81) */
  isMotionFour?: boolean;
  /** Особая группа глаголов состояния (жат, отыр, тұр, жүр — для тем 76–82) */
  isStateFour?: boolean;
  /** Подходящие по смыслу существительные-дополнения (id корней) для многословных ступеней */
  compatibleObjects?: string[];
}

/** 10 личных строк с простыми ↓ и почтительными ↑ стрелками */
export type PersonId =
  | 'men'         // мен (я)
  | 'sen'         // сен ↓ (ты)
  | 'siz'         // сіз ↑ (Вы — один человек, почтительно)
  | 'biz'         // біз (мы)
  | 'ol'          // ол ↓ (он / она / оно)
  | 'ol_kisi'     // ол кісі ↑ (тот уважаемый человек)
  | 'sender'      // сендер ↓↓ (вы — много людей, просто)
  | 'sizder'      // сіздер ↑↑ (Вы — много людей, почтительно)
  | 'olar'        // олар ↓↓ (они — просто)
  | 'ol_kisiler'; // ол кісілер ↑↑ (они — почтительно)

/** Метаданные лица для отображения на экране и в карточках */
export interface PersonMeta {
  id: PersonId;
  pronounKz: string;
  genitiveKz: string;
  dativeKz: string;
  locativeKz: string;
  ablativeKz: string;
  instrumentalKz: string;
  accusativeKz: string;
  arrow: '' | '↓' | '↑' | '↓↓' | '↑↑';
  labelRu: string;
  /** Входит ли в основные 8 лиц для ступени 4 */
  isCoreEight: boolean;
}

/** Цветовая разметка морфемного кусочка по ряду гласных и роли */
export type TenColor =
  | 'red'    // твёрдые гласные, твёрдые слова и окончания, ғ, қ
  | 'green'  // мягкие гласные, мягкие слова и окончания, г, к
  | 'amber'  // смешанные и, у, ю и окончания без твёрдого/мягкого варианта (-нікі, -мен)
  | 'blue'   // одиночные согласные кусочки (й, вставное н) и выпадающие/сливающиеся буквы
  | 'ink';   // общие для обоих рядов кусочки (-м, -ң, -р, -п, ғой/қой, стрелки)

/** Один раскрашенный кусочек слова или фразы в Фазе Б («После проверки») */
export interface ColoredSegment {
  text: string;
  color: TenColor;
  /** Буквальное значение кусочка по-русски («пить», «предстоящее», «моё», «приходит») */
  glossRu: string;
  /** Роль кусочка: корень, суффикс формулы, сквозной кубик, вспомогательное слово, частица */
  role: 'pronoun' | 'root' | 'suffix' | 'core_block' | 'auxiliary' | 'particle';
  /** Если этот кусочек относится к сквозному базовому кубику (КБ-1 … КБ-9) */
  coreBlockId?: CoreBlockId;
  /** Необязательное слово, которое в книге стоит в скобках: (менің), (мен), (егер), (мүмкін) */
  isOptionalBracket?: boolean;
}

/** Овальная капсула звукового слияния на стыке (К30): например «п + а = ба» или «ы + й = и» */
export interface BoundaryMergerCapsule {
  /** Что было до слияния: «тап + а» */
  beforePieces: string;
  /** Формула в овале: «п + а = ба» */
  ovalFormula: string;
  /** Что получилось после слияния: «таба» */
  mergedResult: string;
  /** Простое объяснение без терминов */
  explanationRu: string;
}

/** 9 сквозных базовых кубиков языка (К31) */
export type CoreBlockId =
  | 'KB-1' // Ряд гласных слова (твёрдые а,о,ұ,ы / мягкие ә,е,ө,ү,і / смешанные и,у)
  | 'KB-2' // Личные хвосты принадлежности («чьё»: -м/-ым/-ім, -ң/-ың/-ің, -ңыз/-ыңыз, -сы/-ы)
  | 'KB-3' // Полные личные окончания (-мын/-мін, -бын/-бін, -пын/-пін, -сың/-сің, -сыз/-сіз)
  | 'KB-4' // Короткие личные окончания (-м, -ң, -ңыз/-ңіз, -қ/-к — после -ды/-ді и -са/-се)
  | 'KB-5' // Множественное число (лар/лер, дар/дер, тар/тер)
  | 'KB-6' // Вопросительная частица (ма/ме, ба/бе, па/пе)
  | 'KB-7' // Отрицательный кусочек глагола (ма/ме, ба/бе, па/пе и май/мей, бай/бей, пай/пей)
  | 'KB-8' // 6 падежных хвостов (включая зелёные кружки ①②③ после принадлежности)
  | 'KB-9'; // Слияния и озвончения на стыке (п→б, қ→ғ, к→г, ы+й→и, й+а→я, ы+у→у)

/** Паспорт сквозного базового кубика (К31) */
export interface CoreBlockPassport {
  id: CoreBlockId;
  /** Имя кубика простыми словами (из «Словарика своих имён», К6) */
  defaultTitleRu: string;
  /** Короткая формула-памятка */
  shortFormula: string;
  /** Буквальное объяснение без терминов */
  explanationRu: string;
  /** Сравнение с русским / английским / французским */
  comparisonRu: string;
  /** В каких темах книги впервые вводится и где чаще всего встречается */
  primaryTopicNumber: number;
}

/** Вариант кнопки на ступени 1 («Узнай и выбери кусочек») */
export interface ChoiceOption {
  value: string;
  isCorrect: boolean;
  /** Почему этот вариант верный или почему он сюда не подходит (одной строкой без терминов) */
  reasonRu: string;
}

/** Вид задания в Фазе А («До ответа», К28 — монохромный, без цветовой подсказки) */
export interface BeforeCheckView {
  /** Мысль по-русски сверху (например: «Я хочу выпить») */
  promptRu: string;
  /** Подсказка лица со стрелкой вежливости («мен», «сен ↓», «сіз ↑») */
  personHint: string;
  /**
   * Заготовка по-казахски до ответа (монохромная, с пропуском `[ ___ ]` для ступеней 1–2):
   * например «іш + [ ___ ] + м келеді»
   */
  monochromeStemDisplay: string;
  /** Тихая подпись перевода корня («іш — пить»), пока корень не отмечен как «знаю» (К32) */
  rootTranslationHint: string;
  /** Варианты кнопок для ступени 1 (например: ғы, гі, қы, кі) */
  stage1Options: ChoiceOption[];
  /** Пошаговые шаги, если в формуле 2–3 кусочка подряд (К33 п. 4) */
  multiStepBlanks?: {
    stepIndex: number;
    stepTitleRu: string;
    stemDisplay: string;
    correctPiece: string;
    options: ChoiceOption[];
  }[];
}

/** Вид задания в Фазе Б («После проверки», К28, К30 — с цветами книги и капсулой слияния) */
export interface AfterCheckView {
  /** Основная собранная форма без необязательных скобок (например: «ішкім келеді») */
  canonicalFormKz: string;
  /** Полная форма со словом из скобок (например: «менің ішкім келеді») */
  fullFormWithBracketsKz?: string;
  /** Все допустимые варианты написания (со скобками, без скобок, синонимичные формы по К33) */
  acceptedFormsKz: string[];
  /** Разбивка по морфемным кусочкам с цветами для отображения после проверки */
  coloredSegments: ColoredSegment[];
  /** Строка вида «іш + кі + м + келеді → ішкім келеді» */
  formulaChainText: string;
  /** Буквальный перевод по кусочкам («ко мне приходит моё „попить“») */
  literalMeaningRu: string;
  /** Капсула слияния в овальной рамке, если на стыке изменились буквы (К30) */
  mergerCapsule?: BoundaryMergerCapsule;
  /** Объяснение выбора главного кусочка одной строкой («іш — мягкий ряд, ш — без голоса → кі») */
  selectionRuleSummaryRu: string;
  /** Метка происхождения примера (К20, раздел 9 концепта) */
  sourceBadge: string;
}

/** Полный результат сборки одной формы сборщиком форм */
export interface BuiltFormResult {
  formulaId: string;
  topicNumber: number;
  rootId: string;
  person: PersonId;
  sentenceType: 'affirmative' | 'negative' | 'question';
  beforeCheck: BeforeCheckView;
  afterCheck: AfterCheckView;
}

/** Карточка смысловой формулы (Слой 1 + связь со Слоем 2 и 3) */
export interface FormulaCard {
  /** Внутренний идентификатор формулы (например, 'T83_WANT_PRESENT') */
  id: string;
  /** Номер темы старого адаптера; 0 — самостоятельная карточка без номера книги. */
  topicNumber: number;
  /** Глава старого адаптера; 0 — самостоятельная карточка без главы книги. */
  chapterNumber: number;
  /** Главная мысль по-русски («Хочу сделать», «Могу / умею делать», «У меня (при себе) есть») */
  thoughtTitleRu: string;
  /** Дополнительные поисковые фразы для поля «Хочу сказать…» */
  searchPhrasesRu: string[];
  /** Смысловая группа на главном экране (раздел 2.3 концепта) */
  meaningCluster:
    | 'wish_need_can'    // Желание, возможность, необходимость
    | 'time_action'      // Время и характер действия
    | 'condition_link'   // Условие, причина, одновременность
    | 'possession_place' // Принадлежность, наличие, падежи
    | 'person_politeness'// Лица, вежливость, базовые связки
    | 'participle_desc'; // Описание предмета через действие («сделавший», «который сделал»)
  /** Короткая формула из кусочков своими словами */
  formulaPatternDisplay: string;
  /** Живой образ-крючок и сравнение с русским / английским / французским без терминов */
  hookAndComparisonRu: string;
  /** Как выбирается кусочек (таблица 2×2 или 2×3 простыми словами) */
  pieceSelectionGuideRu: string;
  /** Какие сквозные базовые кубики (КБ-1…КБ-9) работают внутри этой формулы (К31) */
  requiredCoreBlocks: CoreBlockId[];
  /** На какие темы опирается («нужно до» — для мягкой развилки К33 п. 5) */
  prerequisiteTopics: number[];
  /** Соседние темы той же мысли («рядом» — отрицание, вопрос, другое время) */
  neighborTopics: number[];
  /** Равнозначные синонимичные формулы для свободных ступеней 6–8 (К33 п. 3) */
  synonymFormulaIds?: string[];
  /** Обратный порядок слов со стрелкой влево ← (для глав 14–15, 24–25, К30) */
  hasReverseArrowOrder?: boolean;
}
