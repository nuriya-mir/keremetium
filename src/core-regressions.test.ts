import { isNominalTopic, nominalRootIds } from './layer2-kazakh/nominal-lexicon';
import assert from 'node:assert/strict';
import { buildForm } from './layer2-kazakh/form-builder';
import { pickPluralSuffix, pickPossessiveSuffix } from './layer2-kazakh/phonetics';
import { getCaseVariants } from './layer2-kazakh/case-reference';
import { getFormulaSegments } from './layer2-kazakh/formula-segments';
import { checkUserAnswer } from './layer4-engine/answer-checker';
import { FORMULA_CARDS, FORMULAS_BY_ID } from './layer1-meanings/formulas';
import { ROOTS_BY_ID, PERSONS } from './layer2-kazakh/roots';
import { PersonId } from './types';

// Independent normative examples, not snapshots generated by the implementation.
// Abai Institute: https://oq.gov.kz/abai/zhalghau-koptik-dgalghau-zhiktik-dgalghau
// Sound groups: https://corp.soyle.kz/article/view?id=62 (Көптік жалғау).
const pluralExamples = [
  ['үй', 'үйлер'], ['қала', 'қалалар'], ['кітап', 'кітаптар'],
  ['дәстүр', 'дәстүрлер'], ['талдау', 'талдаулар'], ['маман', 'мамандар'],
  ['бөлім', 'бөлімдер'], ['қағаз', 'қағаздар'], ['құжат', 'құжаттар'],
  ['психолог', 'психологтар'],
] as const;
for (const [stem, expected] of pluralExamples) {
  assert.equal(stem + pickPluralSuffix(stem).suffix, expected);
}
// Independent choice rules cover each member of the previously conflated UI group.
for (const [stem, suffix] of [['үй', 'лер'], ['тау', 'лар'], ['би', 'лер'], ['аю', 'лар']] as const) {
  assert.equal(pickPluralSuffix(stem).suffix, suffix);
}
assert.equal(pickPossessiveSuffix('су', 'men').suffix, 'ым', 'Plural fix must not change possessive sound classes');

for (const formulaId of ['', 'UNKNOWN', 'toString', '__proto__']) {
  assert.throws(() => buildForm(formulaId, 'bar'), RangeError);
}
for (const rootId of ['', 'UNKNOWN', 'toString', '__proto__']) {
  assert.throws(() => buildForm('T83_WANT_PRESENT', rootId), RangeError);
}
assert.throws(() => buildForm('T83_WANT_PRESENT', 'bar', 'UNKNOWN' as PersonId), RangeError);

const want = buildForm('T83_WANT_PRESENT', 'bar', 'men');
const tail = want.afterCheck.canonicalFormKz.slice(3);
// Input typos only: the expected grammatical answer is always built by the core.
for (const mistypedRoot of ['абр', 'баар', 'бр', 'бэр']) {
  const result = checkUserAnswer(mistypedRoot + tail, want);
  assert.equal(result.status, 'correct_with_root_typo', mistypedRoot);
  assert.equal(result.diagnostic?.kind, 'root');
  assert.equal(result.diagnostic?.expectedText, ROOTS_BY_ID.bar.kz);
}
const badSuffix = checkUserAnswer(ROOTS_BY_ID.bar.kz + 'қ' + tail.slice(1), want);
assert.equal(badSuffix.isPassed, false, 'Suffix error must never be accepted as a root typo');
assert.equal(badSuffix.diagnostic?.kind, 'suffix');
const changedBoundary = checkUserAnswer('бат' + tail, want);
assert.equal(changedBoundary.isPassed, false, 'Changed root boundary may change suffix selection');
const anotherRoot = checkUserAnswer(ROOTS_BY_ID.ber.kz + tail, want);
assert.equal(anotherRoot.isPassed, false, 'Another known action is not a typo');

let personChecks = 0;
const trained = ['T83_WANT_PRESENT', 'T72_CAN_PRESENT', 'T93_NEED_KEREK', 'T26_PRES_FUT_AFF', 'T31_PAST_DY'];
for (const id of trained) {
  assert(FORMULAS_BY_ID[id], id);
  const expected = buildForm(id, 'bar', 'men');
  const other = buildForm(id, 'bar', 'sen');
  const outcome = checkUserAnswer(other.afterCheck.canonicalFormKz, expected);
  assert.equal(outcome.isPassed, false, id);
  assert.equal(outcome.diagnostic?.kind, 'person', id);
  assert.equal(outcome.diagnostic?.expectedPerson, 'men');
  assert.equal(outcome.diagnostic?.actualPerson, 'sen');
  assert.notEqual(outcome.triggeredCoreBlockId, 'KB-1');
  personChecks++;
}
assert.equal(personChecks, 5);
const negativeNeed = buildForm('T94_NEED_NEG_MAU_KEREK', 'bar', 'sen');
assert.match(negativeNeed.beforeCheck.promptRu, /^Тебе нужно не /);
assert.doesNotMatch(FORMULAS_BY_ID.T94_NEED_NEG_MAU_KEREK.thoughtTitleRu, /(?:^| )не нужно|нельзя/);

const inventories = {
  genitive: ['ның', 'нің', 'дың', 'дің', 'тың', 'тің'],
  dative: ['ға', 'ге', 'қа', 'ке', 'а', 'е', 'на', 'не'],
  locative: ['да', 'де', 'та', 'те', 'нда', 'нде'],
  ablative: ['дан', 'ден', 'тан', 'тен', 'нан', 'нен'],
  instrumental: ['мен', 'бен', 'пен'],
  accusative: ['ны', 'ні', 'ды', 'ді', 'ты', 'ті', 'н'],
  niki: ['нікі', 'дікі', 'тікі'],
};
for (const type of Object.keys(inventories) as Array<keyof typeof inventories>) {
  const variants = getCaseVariants(type);
  assert.deepEqual(variants.map(item => item.suffix), inventories[type]);
  for (const variant of variants) {
    assert(variant.conditionRu && variant.examples.length, `${type}: ${variant.suffix}`);
    for (const example of variant.examples) assert.equal(example.form, example.stem + variant.suffix);
  }
}

let segmentChecks = 0;
for (const card of FORMULA_CARDS) {
  for (const root of Object.values(ROOTS_BY_ID)) {
    if (isNominalTopic(card.id) && !nominalRootIds(card.id).includes(root.id)) continue;
    for (const person of Object.values(PERSONS).filter(person => person.isCoreEight)) {
      const built = buildForm(card.id, root.id, person.id);
      const segments = getFormulaSegments(built).filter(segment => !segment.optional);
      const reconstructed = segments.map((segment, index) => (index && segment.separatorBefore === 'space' ? ' ' : '') + segment.text).join('');
      assert.equal(reconstructed, built.afterCheck.canonicalFormKz, `${card.id} / ${root.id} / ${person.id}`);
      segmentChecks++;
    }
  }
}
console.log(`PASS: ${pluralExamples.length} normative plural fixtures; UI groups; unknown IDs; 4 three-letter root typos; suffix separation; ${personChecks} wrong-person cases; 39 case variants; ${segmentChecks} canonical segment reconstructions.`);
